"""构建系统核心业务异常体系。

本模块定义领域层统一的异常继承树，供配置、规划、源码、工具执行、产物校验、
发布与兼容协议等子系统抛出。异常类本身不包含重试、日志或外部系统调用逻辑；
调用方应使用标准 ``raise ... from`` 保留底层原因。导入本模块不会产生副作用。
"""

from __future__ import annotations


class BuildError(Exception):
    """构建系统业务异常的根类型。

    职责：
        作为所有可预期构建失败的公共基类，便于上层统一捕获与分类处理。

    参数：
        继承 ``Exception`` 的标准构造参数（``message``、可选 ``args``）。

    返回：
        无；本类为异常类型，不作为普通返回值使用。

    异常：
        自身即异常；不在构造阶段再抛出其他异常。

    约束与副作用：
        领域层不得用本类包装外部系统副作用；消息应可复现且不包含密钥。
        实例化与抛出本身不产生 I/O 或状态变更。
    """


class ConfigurationError(BuildError):
    """配置无效或缺失时抛出的业务异常。

    职责：
        表示构建请求、工具链、路径或环境配置无法通过校验，导致无法进入规划。

    参数：
        继承 ``BuildError`` / ``Exception`` 的标准构造参数。

    返回：
        无；本类为异常类型。

    异常：
        自身即异常；不在构造阶段再抛出其他异常。

    约束与副作用：
        仅描述配置类失败；不得用于工具执行超时或产物校验失败。无外部副作用。
    """


class PlanningError(BuildError):
    """任务规划或 DAG 构建失败时抛出的业务异常。

    职责：
        表示依赖环、未知任务、身份冲突或分层失败等规划阶段错误。

    参数：
        继承 ``BuildError`` / ``Exception`` 的标准构造参数。

    返回：
        无；本类为异常类型。

    异常：
        自身即异常；不在构造阶段再抛出其他异常。

    约束与副作用：
        仅描述规划阶段失败；不得递归重启完整构建流水线。无外部副作用。
    """


class SourceError(BuildError):
    """源码或输入快照不可用时抛出的业务异常。

    职责：
        表示 revision、工作区快照或输入资源缺失、损坏或与请求不一致。

    参数：
        继承 ``BuildError`` / ``Exception`` 的标准构造参数。

    返回：
        无；本类为异常类型。

    异常：
        自身即异常；不在构造阶段再抛出其他异常。

    约束与副作用：
        领域层抛出本异常时不应直接调用 SVN；适配器层负责映射外部错误。
        无外部副作用。
    """


class ToolExecutionError(BuildError):
    """外部或内部工具执行失败时抛出的业务异常。

    职责：
        表示 Unity、脚本或其他工具进程非零退出、超时或协议不符。

    参数：
        继承 ``BuildError`` / ``Exception`` 的标准构造参数。

    返回：
        无；本类为异常类型。

    异常：
        自身即异常；不在构造阶段再抛出其他异常。建议用 ``raise ... from``
        保留底层 ``OSError`` / ``TimeoutError`` 等 cause。

    约束与副作用：
        捕获后不得递归重启完整构建流水线；失败应停止当前执行并记录节点状态。
        异常类本身无外部副作用。
    """


class ArtifactValidationError(BuildError):
    """产物元数据或 Blob 校验失败时抛出的业务异常。

    职责：
        表示逻辑路径、哈希、大小、依赖集合或 metadata 不变量被违反。

    参数：
        继承 ``BuildError`` / ``Exception`` 的标准构造参数。

    返回：
        无；本类为异常类型。

    异常：
        自身即异常；不在构造阶段再抛出其他异常。

    约束与副作用：
        仅描述产物与校验失败；不得用于发布激活或兼容协议编码错误。
        无外部副作用。
    """


class PublishError(BuildError):
    """发布、激活或回滚失败时抛出的业务异常。

    职责：
        表示 ReleaseBundle 组装、CDN 上传、激活切换或回滚流程无法完成。

    参数：
        继承 ``BuildError`` / ``Exception`` 的标准构造参数。

    返回：
        无；本类为异常类型。

    异常：
        自身即异常；不在构造阶段再抛出其他异常。

    约束与副作用：
        发布模型与构建产物模型分离；本异常不表示旧客户端协议编码错误。
        异常类本身无外部副作用。
    """


class CompatibilityError(BuildError):
    """旧客户端兼容协议生成或校验失败时抛出的业务异常。

    职责：
        表示 ``assetbundledb``、六字段文件列表、Redirect 或分包 bit flag 等
        兼容输出无法从上游 Release 模型确定性生成或未通过 Golden 校验。

    参数：
        继承 ``BuildError`` / ``Exception`` 的标准构造参数。

    返回：
        无；本类为异常类型。

    异常：
        自身即异常；不在构造阶段再抛出其他异常。

    约束与副作用：
        旧协议只能由 ``compatibility`` 模块生成；领域层不应直接拼协议文本。
        异常类本身无外部副作用。
    """
