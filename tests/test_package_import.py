"""验证 ``st.build`` 顶级包的最小公共导入契约。

本模块只覆盖第一阶段工程骨架必须提供的包可导入性和版本号，不验证尚未实现的构建、
发布或兼容协议能力。测试不访问外部系统、不写入业务文件，也不依赖旧构建目录。
"""


def test_package_exposes_version() -> None:
    """验证导入 ``st.build`` 后公开固定的初始版本号。

    测试无参数和返回值；当包尚不存在、无法导入或版本号不为 ``0.1.0`` 时由 pytest
    报告失败。除 Python 正常的模块导入缓存外，本测试不产生外部副作用。
    """
    import st.build

    assert st.build.__version__ == "0.1.0"
